# PCOS Severity Classification – Medically Weighted Version

# Step 1: Libraries
import pandas as pd, numpy as np
import matplotlib.pyplot as plt, seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score

from google.colab import files
uploaded = files.upload()
# Step 2: Load Data
df = pd.read_excel("pcnos.xlsx")

print("Shape after loading data:", df.shape)
print("Columns after loading data:", df.columns.tolist())


df = df.replace(['?', 'NA', 'NaN', ' '], np.nan)

cols = [
    ' Age (yrs)', 'BMI', 'Weight (Kg)', 'Weight gain(Y/N)', 'hair growth(Y/N)',
    'Skin darkening (Y/N)', 'Hair loss(Y/N)', 'Pimples(Y/N)',
    'Cycle(R/I)', 'Cycle length(days)',
    'FSH(mIU/mL)', 'LH(mIU/mL)', 'AMH(ng/mL)', 'TSH (mIU/L)', 'PRL(ng/mL)'
]

df = df[cols]


df = df.dropna()



# Step 5: Encode binary columns
bin_cols = ['Weight gain(Y/N)', 'hair growth(Y/N)', 'Skin darkening (Y/N)',
            'Hair loss(Y/N)', 'Pimples(Y/N)', 'Cycle(R/I)']

enc = LabelEncoder()
for c in bin_cols:
    df[c] = enc.fit_transform(df[c].astype(str))

# Step 6: Derived Features
df['LH_FSH_ratio'] = df['LH(mIU/mL)'] / df['FSH(mIU/mL)']

# Step 7: Weighted Severity Scoring
def compute_weighted_score(row):
    score = 0

    # Hormonal
    if row['LH_FSH_ratio'] > 2: score += 2
    if row['AMH(ng/mL)'] > 5: score += 2
    if row['TSH (mIU/L)'] > 4 or row['PRL(ng/mL)'] > 25: score += 1

    # Cycle
    if row['Cycle(R/I)'] == 1 or row['Cycle length(days)'] > 35: score += 2

    # Metabolic
    if row['BMI'] > 30: score += 2
    elif row['BMI'] > 25: score += 1

    # Physical symptoms
    symptom_cols = ['Weight gain(Y/N)', 'hair growth(Y/N)',
                    'Skin darkening (Y/N)', 'Hair loss(Y/N)', 'Pimples(Y/N)']
    score += 0.5 * sum(row[c] for c in symptom_cols)

    return score

df['Severity_Score'] = df.apply(compute_weighted_score, axis=1)

def map_severity(s):
    if s <= 3: return 'Mild'
    elif s <= 6: return 'Moderate'
    else: return 'Severe'

df['Severity'] = df['Severity_Score'].apply(map_severity)

# Step 8: Prepare Data
X = df.drop(['Severity', 'Severity_Score'], axis=1)
y = df['Severity']

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42, stratify=y)

# Step 9: Train Random Forest
rf = RandomForestClassifier(n_estimators=150, random_state=42)
rf.fit(X_train, y_train)

# Step 10: Evaluate
y_pred = rf.predict(X_test)
print("Accuracy:", accuracy_score(y_test, y_pred))
print("\nClassification Report:\n", classification_report(y_test, y_pred))

# Step 11: Confusion Matrix
sns.heatmap(confusion_matrix(y_test, y_pred), annot=True, cmap='pink', fmt='d')
plt.title("Confusion Matrix – PCOS Severity (Weighted)")
plt.show()

# Step 12: Feature Importance
imp = pd.Series(rf.feature_importances_, index=X.columns).sort_values(ascending=False)
imp.head(10).plot(kind='barh', color='hotpink')
plt.title("Top 10 Important Features")
plt.show()

# Step 13: Save the model and scaler
import joblib
joblib.dump(rf, "pcos_severity_model.pkl")
joblib.dump(scaler, "scaler.pkl")

